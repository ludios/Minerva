#!/usr/bin/env python3
"""
Generate js_minerva/cw/net/autocachebreakers.js, which gives the JavaScript
client cache breakers (MD5 digests) for files it loads, like the Flash
connector.  Run this after rebuilding FlashConnector.swf.
"""

import hashlib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / "js_minerva" / "cw" / "net" / "autocachebreakers.js"
# JavaScript property name -> the file to make a cache breaker for
BREAKERS = {
    "cw.net.breaker_FlashConnector_swf": REPO
    / "src/minerva/compiled_client/FlashConnector.swf",
}


def generate() -> str:
    provides = "".join(f"goog.provide('{name}');\n" for name in BREAKERS)
    assignments = "".join(
        f"{name} = '{hashlib.md5(path.read_bytes()).hexdigest()}';\n"
        for name, path in BREAKERS.items()
    )
    return (
        "/**\n"
        " * DO NOT EDIT.  Generated by scripts/build_autocachebreakers.py.\n"
        " */\n"
        "\n"
        f"{provides}\n{assignments}"
    )


def main() -> None:
    content = generate()
    # Don't touch an identical file, to avoid triggering JavaScript rebuilds.
    if not OUTPUT.exists() or OUTPUT.read_text() != content:
        OUTPUT.write_text(content)
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
